func TestExtractValidationURL(t *testing.T) {
	tests := []struct {
		name     string
		body     string
		expected string
	}{
		{
			name:     "structured validation_url",
			body:     `{"error":{"details":[{"metadata":{"validation_url":"https://accounts.google.com/verify?token=abc"}}]}}`,
			expected: "https://accounts.google.com/verify?token=abc",
		},
		{
			name:     "structured appeal_url",
			body:     `{"error":{"details":[{"metadata":{"appeal_url":"https://support.google.com/appeal/123"}}]}}`,
			expected: "https://support.google.com/appeal/123",
		},
		{
			name:     "validation_url takes priority over appeal_url",
			body:     `{"error":{"details":[{"metadata":{"validation_url":"https://v.com","appeal_url":"https://a.com"}}]}}`,
			expected: "https://v.com",
		},
		{
			name:     "fallback regex with verify keyword",
			body:     `Please verify your account at https://accounts.google.com/verify`,
			expected: "https://accounts.google.com/verify",
		},
		{
			name:     "no URL in generic forbidden",
			body:     `Access denied`,
			expected: "",
		},
		{
			name:     "empty body",
			body:     "",
			expected: "",
		},
		{
			name:     "URL present but no validation keywords",
			body:     `Error at https://example.com/something`,
			expected: "",
		},
		{
			name:     "unicode escaped ampersand",
			body:     `validation required: https://accounts.google.com/verify?a=1\u0026b=2`,
			expected: "https://accounts.google.com/verify?a=1&b=2",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := extractValidationURL(tt.body)
			require.Equal(t, tt.expected, got)
		})
	}
}

func TestFetchAntigravitySharedQuota(t *testing.T) {
	for _, forbidden := range []bool{false, true} {
		t.Run(map[bool]string{false: "shared windows", true: "verification required"}[forbidden], func(t *testing.T) {
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				switch r.URL.Path {
				case "/v1internal:retrieveUserQuotaSummary":
					if forbidden {
						w.WriteHeader(http.StatusForbidden)
						_, _ = w.Write([]byte(`{"error":{"message":"VALIDATION_REQUIRED"}}`))
						return
					}
					_, _ = w.Write([]byte(`{"buckets":[{"bucketId":"gemini-5h","remainingFraction":0.4},{"bucketId":"gemini-weekly","remainingFraction":0.1},{"bucketId":"3p-5h","remainingFraction":1},{"bucketId":"3p-weekly","remainingFraction":0.5}]}`))
				case "/v1internal:loadCodeAssist":
					_, _ = w.Write([]byte(`{"currentTier":{"id":"g1-pro-tier"}}`))
				default:
					t.Errorf("unexpected quota request: %s", r.URL.Path)
					w.WriteHeader(http.StatusNotFound)
				}
			}))
			defer server.Close()
			original := antigravity.BaseURLs
			availability := antigravity.DefaultURLAvailability
			antigravity.BaseURLs = []string{server.URL}
			antigravity.DefaultURLAvailability = antigravity.NewURLAvailability(time.Minute)
			t.Cleanup(func() { antigravity.BaseURLs = original; antigravity.DefaultURLAvailability = availability })
			result, err := (&AntigravityQuotaFetcher{}).FetchQuota(context.Background(), &Account{
				Platform: PlatformAntigravity, Credentials: map[string]any{"access_token": "token", "project_id": "project"},
			}, "")
			require.NoError(t, err)
			if forbidden {
				require.True(t, result.UsageInfo.NeedsVerify)
				require.True(t, result.UsageInfo.IsForbidden)
				return
			}
			require.Equal(t, "PRO", result.UsageInfo.SubscriptionTier)
			require.Equal(t, "available", result.UsageInfo.AntigravityQuotaSummaryStatus)
			require.Len(t, result.UsageInfo.AntigravityQuotaGroups, 2)
			require.Len(t, result.UsageInfo.AntigravityQuotaGroups[0].Buckets, 2)
			require.Len(t, result.UsageInfo.AntigravityQuotaGroups[1].Buckets, 2)
		})
	}
}
